-- ------------------------------------------------------------------
-- VERIFICAR
-- ------------------------------------------------------------------
-- 1. Uma alteração a um animal escreve uma linha com o autor certo:
--
--   update public.animal set nome = nome || ' ' where id = '<id>';
--   select em, tabela, acao, resumo, user_id from public.registo_atividade
--    order by em desc limit 5;
--
-- 2. Reenviar a MESMA linha não escreve nada (é o caso da sincronização):
--
--   update public.animal set updated_at = now() where id = '<id>';
--   -- a contagem de linhas do registo tem de ficar igual
--
-- 3. Um trabalhador vê só o que ele próprio fez; o dono vê tudo. Na sessão do
--    trabalhador:
--
--   select count(*) from public.registo_atividade;
--
-- 4. Ninguém consegue escrever à mão no registo (tem de dar "permission denied"):
--
--   insert into public.registo_atividade (exploracao_id, tabela, acao)
--   values ('<exploracao>', 'animal', 'criou');
